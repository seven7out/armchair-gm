import { ContractYear, LeagueYear, Player, PositionGroup, PlayerTier, TeamSeedData } from '@/engine/types';

/**
 * Helper to concisely create a ContractYear
 */
function cy(
  year: LeagueYear,
  baseSalary: number,
  guaranteedSalary: number,
  proratedBonus: number,
  rosterBonus: number = 0,
  workoutBonus: number = 0,
  isVoidYear: boolean = false,
  isFifthYearOption: boolean = false
): ContractYear {
  return {
    year,
    baseSalary,
    guaranteedSalary,
    proratedBonus,
    rosterBonus,
    workoutBonus,
    isVoidYear,
    isFifthYearOption,
  };
}

/**
 * Helper to generate realistic depth/rotation players to round out a full NFL roster
 * so Top-51 displacement and multi-year horizon depth charts behave authentically.
 */
function makeDepthPlayer(
  id: string,
  name: string,
  position: PositionGroup,
  ageIn2026: number,
  overallRating: number,
  tier: PlayerTier,
  accruedSeasons: number,
  y2026: [number, number, number] | null,
  y2027: [number, number, number] | null = null,
  y2028: [number, number, number] | null = null,
  y2029: [number, number, number] | null = null,
  notes?: string
): Player {
  return {
    id,
    name,
    position,
    ageIn2026,
    tier,
    overallRating,
    accruedSeasons,
    notes,
    contractYears: {
      2026: y2026 ? cy(2026, y2026[0], y2026[1], y2026[2]) : null,
      2027: y2027 ? cy(2027, y2027[0], y2027[1], y2027[2]) : null,
      2028: y2028 ? cy(2028, y2028[0], y2028[1], y2028[2]) : null,
      2029: y2029 ? cy(2029, y2029[0], y2029[1], y2029[2]) : null,
    },
  };
}

